// Applies the Classic UI changes to a Homunculus checkout: public/index.html plus a few small,
// flag-guarded switches in Homunculus scripts (globalThis.HomunculusClassicUi, set in index.html).
// Pattern-based (tolerates version query strings changing between Homunculus releases) and idempotent.
// Usage: node classic-ui/apply-classic.mjs   (or: bun classic-ui/apply-classic.mjs)
import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const indexPath = path.join(repoRoot, 'public', 'index.html');
let html = fs.readFileSync(indexPath, 'utf8');

const problems = [];
const alreadyApplied = html.includes('scripts/classic-ui.js');
const V = '(?:\\?[^"]*)?'; // optional ?v=... cache-busting suffix

function replace(label, pattern, replacement, { required = true } = {}) {
    const before = html;
    html = html.replace(pattern, replacement);
    if (required && before === html) {
        problems.push(label);
    }
}

if (!alreadyApplied) {
// 1. Stop loading Homunculus's graphical shell and its stylesheets.
replace('shell modulepreload', new RegExp(`[ \\t]*<link rel="modulepreload" href="scripts/homunculus-tabs\\.js${V}">\\r?\\n`), '');
replace('shell script', new RegExp(`[ \\t]*<script type="module" src="scripts/homunculus-tabs\\.js${V}"></script>\\r?\\n`), '');
for (const sheet of ['homunculus-theme', 'homunculus-paper-theme', 'homunculus-tabs', 'homunculus-mobile-shell']) {
    replace(`${sheet}.css`, new RegExp(`[ \\t]*<link rel="stylesheet" type="text/css" href="css/${sheet}\\.css${V}"[^>]*>\\r?\\n`), '');
}

// 2. SillyTavern-styled stylesheets (generated by classic-ui/tools/build-css.sh).
replace('style.css', new RegExp(`href="style\\.css${V}"`, 'g'), 'href="style-classic.css"');
for (const sheet of ['st-tailwind', 'toggle-dependent', 'select2-overrides', 'mobile-styles']) {
    replace(`${sheet}.css`, new RegExp(`href="css/${sheet}\\.css${V}"`), `href="css/classic--${sheet}.css"`);
}

// 3. Fonts load like upstream SillyTavern (swap instead of deferred/optional).
for (const font of ['NotoSans', 'NotoSansMono']) {
    replace(`${font} font`, new RegExp(`<link href="webfonts/${font}/stylesheet\\.css${V}"[^>]*>`), `<link href="webfonts/${font}/classic-stylesheet.css" rel="stylesheet">`);
}
replace('brands.min.css', new RegExp(`<link href="css/brands\\.min\\.css${V}"[^>]*>`), '<link href="css/brands.min.css" rel="stylesheet">', { required: false });

// 4. Extra stylesheets, right before user.css so user CSS still wins.
replace('user.css anchor', new RegExp(`([ \\t]*)(<link rel="stylesheet" type="text/css" href="css/user\\.css${V}">)`), [
    '$1<!-- Classic UI fork: SillyTavern loads these up front; Homunculus deferred them through its shell. -->',
    '$1<link rel="stylesheet" type="text/css" href="css/classic--world-info.css">',
    '$1<link rel="stylesheet" type="text/css" href="css/classic--extensions-panel.css">',
    '$1<link rel="stylesheet" type="text/css" href="css/classic-sb-extras.css">',
    '$1<link rel="stylesheet" type="text/css" href="css/classic-ui.css">',
    '$1$2',
].join('\n'));

// 5. Replacement for the shell module.
replace('script.js anchor', new RegExp(`([ \\t]*)(<script type="module" src="script\\.js${V}"></script>)`), [
    '$1$2',
    '$1<!-- Classic UI fork: replaces scripts/homunculus-tabs.js (graphical shell) -->',
    '$1<script type="module" src="scripts/classic-ui.js"></script>',
].join('\n'));

// 6. In-Chat Agents get their own top-bar drawer, next to Persona Management.
replace('persona drawer anchor', /([ \t]*)(<div id="persona-management-button" class="drawer">)/, [
    '$1<!-- Classic UI fork: In-Chat Agents get their own top-bar drawer (in Homunculus they live in the Workspace shell). -->',
    '$1<div id="agents-settings-button" class="drawer">',
    '$1    <div class="drawer-toggle">',
    '$1        <div class="drawer-icon fa-solid fa-robot fa-fw closedIcon" title="In-Chat Agents" data-i18n="[title]In-Chat Agents"></div>',
    '$1    </div>',
    '$1    <div id="rm_agents_block" class="drawer-content closedDrawer">',
    '$1        <div class="agents_drawer_block flex-container flexFlowColumn">',
    '$1            <div class="alignitemscenter flex-container wide100p">',
    '$1                <h3 class="margin0 flex1">In-Chat Agents</h3>',
    '$1            </div>',
    '$1            <div id="in_chat_agents_container" class="wide100p"></div>',
    '$1        </div>',
    '$1    </div>',
    '$1</div>',
    '$1$2',
].join('\n'));

}

// 7. Flag read by the small script switches below; must run before any module.
const hasFlag = html.includes('globalThis.HomunculusClassicUi = true');
if (!hasFlag) {
    replace('head anchor', /([ \t]*)(<meta charset="utf-8">)/, '$1$2\n$1<script>globalThis.HomunculusClassicUi = true; /* Classic UI fork */</script>');
}

// 9c. Group and macro styles: Homunculus defers its own rm-groups.css/macros.css from script.js (patched
// below to skip them); the classic interface links the SillyTavern-styled copies up front instead.
for (const sheet of ['rm-groups', 'macros']) {
    if (!html.includes(`css/classic--${sheet}.css`)) {
        replace(`world-info anchor (${sheet})`, new RegExp(`([ \\t]*)(<link rel="stylesheet" type="text/css" href="css/classic--world-info\\.css${V}">)`),
            `$1<link rel="stylesheet" type="text/css" href="css/classic--${sheet}.css">\n$1$2`);
    }
}

// 9. Visual profiles ("temas"), effects and the Personalização drawer (scripts/classic-themes.js).
// Checked one by one so installs that already have the classic interface also receive it.
// 9a. Stylesheets and scripts of the visual layer, each added once, in this order.
for (const sheet of ['classic-themes', 'classic-layout', 'classic-features']) {
    if (!html.includes(`css/${sheet}.css`)) {
        replace(`user.css anchor (${sheet})`, new RegExp(`([ \\t]*)(<link rel="stylesheet" type="text/css" href="css/user\\.css${V}">)`),
            `$1<link rel="stylesheet" type="text/css" href="css/${sheet}.css">\n$1$2`);
    }
}
let previousScript = 'classic-ui';
for (const script of ['classic-themes', 'classic-home', 'classic-editor', 'classic-quick-connect', 'classic-card-browser', 'classic-memory', 'classic-group-studio', 'classic-scene', 'classic-group-agents']) {
    if (!html.includes(`scripts/${script}.js`)) {
        replace(`${previousScript}.js anchor (${script})`, new RegExp(`([ \\t]*)(<script type="module" src="scripts/${previousScript}\\.js${V}"></script>)`),
            `$1$2\n$1<script type="module" src="scripts/${script}.js"></script>`);
    }
    previousScript = script;
}
if (!html.includes('id="ct-personalize-button"')) {
    replace('backgrounds drawer anchor (themes)', /([ \t]*)(<div id="backgrounds-button" class="drawer">)/, [
        '$1<!-- Classic UI fork: Customize (visual profiles, layout and effects), filled by scripts/classic-themes.js -->',
        '$1<div id="ct-personalize-button" class="drawer">',
        '$1    <div class="drawer-toggle">',
        '$1        <div class="drawer-icon fa-solid fa-palette fa-fw closedIcon" title="Customize"></div>',
        '$1    </div>',
        '$1    <div id="ct_personalize_block" class="drawer-content closedDrawer">',
        '$1        <div id="ct_personalize"></div>',
        '$1    </div>',
        '$1</div>',
        '$1$2',
    ].join('\n'));
}

// 9b. Memory drawer (brain icon, scripts/classic-memory.js): chapter summaries and Recall.
if (!html.includes('id="ct-memory-button"')) {
    replace('persona drawer anchor (memory)', /([ \t]*)(<div id="persona-management-button" class="drawer">)/, [
        '$1<!-- Classic UI fork: Memory (chapters and recall), filled by scripts/classic-memory.js -->',
        '$1<div id="ct-memory-button" class="drawer">',
        '$1    <div class="drawer-toggle">',
        '$1        <div class="drawer-icon fa-solid fa-brain fa-fw closedIcon" title="Memory: chapters and recall"></div>',
        '$1    </div>',
        '$1    <div id="ct_memory_block" class="drawer-content closedDrawer">',
        '$1        <div id="ct_memory"></div>',
        '$1    </div>',
        '$1</div>',
        '$1$2',
    ].join('\n'));
}

// 10. List of built-in profiles: every public/classic-themes/<folder>/theme.json, with a content hash so
// browsers pick up edited themes. Run this script again after adding or editing a theme folder.
const themesDir = path.join(repoRoot, 'public', 'classic-themes');
let themesIndexOutput = null;
if (fs.existsSync(themesDir)) {
    const themes = [];
    for (const entry of fs.readdirSync(themesDir, { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name))) {
        const folder = path.join(themesDir, entry.name);
        if (!entry.isDirectory() || !/^[a-z0-9-]+$/.test(entry.name) || !fs.existsSync(path.join(folder, 'theme.json'))) {
            continue;
        }
        try {
            JSON.parse(fs.readFileSync(path.join(folder, 'theme.json'), 'utf8'));
        } catch (error) {
            problems.push(`classic-themes/${entry.name}/theme.json: ${error.message}`);
            continue;
        }
        const hash = crypto.createHash('sha1');
        const walk = dir => {
            for (const item of fs.readdirSync(dir, { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name))) {
                const full = path.join(dir, item.name);
                if (item.isDirectory()) walk(full);
                else hash.update(item.name).update(fs.readFileSync(full));
            }
        };
        walk(folder);
        themes.push({ id: entry.name, v: hash.digest('hex').slice(0, 10) });
    }
    const indexJson = `${JSON.stringify({ generatedBy: 'classic-ui/apply-classic.mjs', themes }, null, 2)}\n`;
    const indexFile = path.join(themesDir, 'index.json');
    if (!fs.existsSync(indexFile) || fs.readFileSync(indexFile, 'utf8') !== indexJson) {
        themesIndexOutput = [indexFile, indexJson];
    }
}

// Script switches: each is a single, flag-guarded line so Homunculus behaves normally without the flag.
const scriptPatches = [
    {
        file: 'public/scripts/openai.js',
        label: 'flat Chat Completion settings (no collapsible groups)',
        find: /^([ \t]*)groupOpenAISettingsIntoDrawers\(\);$/m,
        replace: '$1if (!globalThis.HomunculusClassicUi) groupOpenAISettingsIntoDrawers(); // Classic UI fork: keep SillyTavern\'s flat layout',
        applied: 'if (!globalThis.HomunculusClassicUi) groupOpenAISettingsIntoDrawers();',
    },
    {
        file: 'public/scripts/world-info.js',
        label: 'World Info entries edited inline (no side editor pane)',
        find: /^const WORLD_INFO_DESKTOP_SPLIT_QUERY = ('[^']*');$/m,
        replace: 'const WORLD_INFO_DESKTOP_SPLIT_QUERY = globalThis.HomunculusClassicUi ? \'not all\' : $1; // Classic UI fork: inline entry editing',
        applied: 'const WORLD_INFO_DESKTOP_SPLIT_QUERY = globalThis.HomunculusClassicUi',
    },
    {
        file: 'public/scripts/PromptManager.js',
        label: 'Prompt Manager list without side editor pane',
        find: /^const PROMPT_MANAGER_DESKTOP_SPLIT_QUERY = ('[^']*');$/m,
        replace: 'const PROMPT_MANAGER_DESKTOP_SPLIT_QUERY = globalThis.HomunculusClassicUi ? \'not all\' : $1; // Classic UI fork: list-only layout',
        applied: 'const PROMPT_MANAGER_DESKTOP_SPLIT_QUERY = globalThis.HomunculusClassicUi',
    },
    {
        file: 'public/scripts/welcome-screen.js',
        label: 'compact home page by default',
        find: /getWelcomeUiPreference\(welcomePanelModeKey\) \|\| WELCOME_PANEL_MODES\.full;/,
        replace: 'getWelcomeUiPreference(welcomePanelModeKey) || (globalThis.HomunculusClassicUi ? WELCOME_PANEL_MODES.compact : WELCOME_PANEL_MODES.full); // Classic UI fork',
        applied: 'globalThis.HomunculusClassicUi ? WELCOME_PANEL_MODES.compact',
    },
];

// Homunculus loads rm-groups.css and macros.css a moment after startup. In the classic interface the
// SillyTavern-styled copies are linked in index.html instead (step 9c), so the deferred loader skips them.
scriptPatches.push({
    file: 'public/script.js',
    label: 'skip deferred group/macro stylesheets',
    find: /^([ \t]*)for \(const stylesheet of DEFERRED_STARTUP_STYLESHEETS\) \{$/m,
    replace: '$1for (const stylesheet of DEFERRED_STARTUP_STYLESHEETS.filter(s => !(globalThis.HomunculusClassicUi && CLASSIC_LINKED_STYLESHEETS.has(s.href)))) { // Classic UI fork: classic copies are linked in index.html',
    applied: 'CLASSIC_LINKED_STYLESHEETS.has(s.href)',
}, {
    file: 'public/script.js',
    label: 'classic linked stylesheets list',
    find: /^(const DEFERRED_STARTUP_STYLESHEETS = Object\.freeze\(\[)$/m,
    replace: "const CLASSIC_LINKED_STYLESHEETS = new Set(['css/rm-groups.css', 'css/macros.css']); // Classic UI fork: see apply-classic.mjs step 9c\n$1",
    applied: 'const CLASSIC_LINKED_STYLESHEETS',
});

// Card Browser: server routes that search the card sites (src/endpoints/classic-card-browser.js).
// Searching from the server avoids third-party CORS proxies: requests go straight to each site.
scriptPatches.push(
    {
        file: 'src/server-startup.js',
        label: 'Card Browser routes (import)',
        find: /^(import \{ router as contentManagerRouter \} from '\.\/endpoints\/content-manager\.js';)$/m,
        replace: '$1\nimport { router as classicCardBrowserRouter } from \'./endpoints/classic-card-browser.js\'; // Classic UI fork: Card Browser',
        applied: 'classicCardBrowserRouter } from',
    },
    {
        file: 'src/server-startup.js',
        label: 'Card Browser routes (mount)',
        find: /^([ \t]*)(app\.use\('\/api\/content', contentManagerRouter\);)$/m,
        replace: '$1$2\n$1app.use(\'/api/classic-cards\', classicCardBrowserRouter); // Classic UI fork: Card Browser',
        applied: "app.use('/api/classic-cards'",
    },
);

const scriptOutputs = [];
const patchedSources = new Map(); // several patches may touch the same file: apply them in sequence
for (const patch of scriptPatches) {
    const filePath = path.join(repoRoot, patch.file);
    const source = patchedSources.get(filePath) ?? fs.readFileSync(filePath, 'utf8');
    if (source.includes(patch.applied)) {
        continue;
    }
    const patched = source.replace(patch.find, patch.replace);
    if (patched === source) {
        problems.push(`${patch.file}: ${patch.label}`);
        continue;
    }
    patchedSources.set(filePath, patched);
}
for (const [filePath, patched] of patchedSources) {
    scriptOutputs.push([filePath, patched]);
}

// 8. Cache busting. Homunculus's service worker serves /css/ and /webfonts/ stale-while-revalidate, so
// a browser that ran Homunculus (or an older classic build) at the same address would keep showing old
// styles. Every classic stylesheet URL carries a hash of its contents; a changed file means a new URL.
const fileHash = rel => crypto.createHash('sha1').update(fs.readFileSync(path.join(repoRoot, 'public', rel))).digest('hex').slice(0, 10);
const styleClassicPath = path.join(repoRoot, 'public', 'style-classic.css');
const styleClassic = fs.readFileSync(styleClassicPath, 'utf8');
const versionedStyleClassic = styleClassic.replace(/@import url\((css\/classic--[^)?]+\.css)(?:\?v=[^)]*)?\);/g,
    (_, rel) => `@import url(${rel}?v=${fileHash(rel)});`);
const versionedHtml = html.replace(/(href=")((?:style-classic|css\/classic[^"?]*|webfonts\/[A-Za-z]+\/classic-stylesheet)\.css)(?:\?v=[^"]*)?"/g,
    (_, prefix, rel) => `${prefix}${rel}?v=${rel === 'style-classic.css' ? crypto.createHash('sha1').update(versionedStyleClassic).digest('hex').slice(0, 10) : fileHash(rel)}"`)
    .replace(/(src=")(scripts\/classic-[a-z-]+\.js)(?:\?v=[^"]*)?"/g, (_, prefix, rel) => `${prefix}${rel}?v=${fileHash(rel)}"`);
const versionChanged = versionedHtml !== html || versionedStyleClassic !== styleClassic;
html = versionedHtml;

if (problems.length) {
    console.error('[Classic] Could not find these parts of Homunculus (they changed in this version):');
    for (const problem of problems) console.error(`  - ${problem}`);
    console.error('[Classic] Nothing was modified.');
    process.exit(1);
}

const htmlChanged = html !== fs.readFileSync(indexPath, 'utf8');
if (!alreadyApplied || !hasFlag || versionChanged || htmlChanged) {
    fs.writeFileSync(indexPath, html);
    fs.writeFileSync(styleClassicPath, versionedStyleClassic);
}
for (const [filePath, contents] of scriptOutputs) {
    fs.writeFileSync(filePath, contents);
}
if (themesIndexOutput) {
    fs.writeFileSync(...themesIndexOutput);
}
console.log(alreadyApplied && hasFlag && !versionChanged && !htmlChanged && !scriptOutputs.length && !themesIndexOutput ? '[Classic] Already applied.' : '[Classic] Classic interface applied.');
